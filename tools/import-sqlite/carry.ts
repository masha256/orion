/**
 * The carry rules (D8, Phase 1 D3a, P1): which SQLite rows go to Postgres. The importer and the proof share them, so
 * what the proof compares is exactly what the importer copied.
 */

/** How a column is held in Postgres, which decides what the importer checks before it writes a value. */
export type ColumnType = 'int' | 'real' | 'text' | 'json' | 'timestamptz' | 'date';

export interface CarriedTable {
  table: string;
  /** Columns in Postgres order (the same as SQLite schema 8's). */
  columns: { name: string; type: ColumnType }[];
  primaryKey: string[];
  /** `id bigint GENERATED BY DEFAULT AS IDENTITY`: the sequence continues at `sqlite_sequence`. */
  identity: boolean;
}

const cols = (spec: string): CarriedTable['columns'] =>
  spec.trim().split(/\s+/).map((c) => {
    const [name, type] = c.split(':') as [string, ColumnType];
    return { name, type };
  });

