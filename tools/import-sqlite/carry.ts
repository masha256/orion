export type ExclusionReason = 'undeclared_metric' | 'undeclared_asset' | 'retired_kind' | 'non_disclosure_transcript';

export interface CarryTable extends CarriedTable {
  /** SQLite SQL: the carried rows, columns in Postgres order, ordered by the primary key. */
  select: string;
  /** Rows left out, by reason; ids are the primary key, ascending. Reasons with no rows are omitted. */
  excluded: { reason: ExclusionReason; ids: (number | string)[] }[];
}
export type CarryPlan = CarryTable[];

/** Which rows of `sqlite` are carried, against the assets' YAML (the release's `metrics`). */
export function carryPlan(sqlite: Database.Database, assets: readonly AssetConfig[]): CarryPlan {
  const declared = new Map(assets.map((a) => [a.id, new Set(Object.keys(a.metrics))]));
  const ids = (sql: string) => (sqlite.prepare(sql).raw().all() as [number][]).map((r) => r[0]);

  const undeclaredMetric: number[] = [];
  const undeclaredAsset: number[] = [];
  for (const [id, asset, metric] of sqlite.prepare('SELECT id, asset_id, metric_key FROM observations ORDER BY id').raw().all() as [number, string, string][]) {
    const metrics = declared.get(asset);
    if (!metrics) undeclaredAsset.push(id);
    else if (!metrics.has(metric)) undeclaredMetric.push(id);
  }
  const exclusions: Record<string, CarryTable['excluded']> = {
    observations: [
      { reason: 'undeclared_metric', ids: undeclaredMetric },
      { reason: 'undeclared_asset', ids: undeclaredAsset },
    ],
    proposals: [{ reason: 'retired_kind', ids: ids("SELECT id FROM proposals WHERE kind = 'assumption_value' ORDER BY id") }],
    agent_transcripts: [
      {
        reason: 'non_disclosure_transcript',
        ids: ids("SELECT t.run_id FROM agent_transcripts t JOIN agent_runs r ON r.id = t.run_id WHERE r.run_type <> 'disclosure' ORDER BY t.run_id"),
      },
    ],
  };

  return CARRIED_TABLES.map((t): CarryTable => {
    const excluded = (exclusions[t.table] ?? []).filter((e) => e.ids.length > 0);
    const left = excluded.flatMap((e) => e.ids);
    // Only single-column integer keys are ever excluded, so the ids are plain integer literals.
    const where = left.length > 0 ? ` WHERE ${t.primaryKey[0]} NOT IN (${[...left].sort((a, b) => Number(a) - Number(b)).join(', ')})` : '';
    return {
      ...t,
      select: `SELECT ${t.columns.map((c) => c.name).join(', ')} FROM ${t.table}${where} ORDER BY ${t.primaryKey.join(', ')}`,
      excluded,
    };
  });
}
