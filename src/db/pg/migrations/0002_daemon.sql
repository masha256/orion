-- 0002_daemon: the daemon's tables (Phase 1.5c, spec sections 5.1-5.3, 5.6, 9.1): jobs, asset registry, latest levels, watch state, day blocks, snapshot outbox, heartbeat.
-- Schema-unqualified: the migrator runs it with search_path set to the target schema. Expand-only.
-- jobs: one row per scheduled or requested run. (kind, asset_id, slot) is unique with NULLs equal (plan R1), so a job
-- without an asset (levels, nightly_report, ...) is still enqueued once per slot.
CREATE TABLE jobs (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  kind text COLLATE "C" NOT NULL CHECK (kind IN ('refresh','nightly_report','levels','snapshot_push','disclosure_watch','staging_refresh','retention')),
  asset_id text COLLATE "C", slot timestamptz NOT NULL, run_after timestamptz NOT NULL, priority smallint NOT NULL,
  status text COLLATE "C" NOT NULL CHECK (status IN ('queued','running','done','failed','skipped')),
  attempts smallint NOT NULL DEFAULT 0, max_attempts smallint NOT NULL,
  lease_owner text COLLATE "C", lease_expires_at timestamptz, started_at timestamptz, ended_at timestamptz,
  result_json json, release_tag text COLLATE "C", requested_by text COLLATE "C" NOT NULL DEFAULT 'scheduler', last_error text COLLATE "C",
  CONSTRAINT jobs_slot_key UNIQUE NULLS NOT DISTINCT (kind, asset_id, slot));
CREATE INDEX idx_jobs_claim ON jobs (status, priority, run_after, id);
-- asset_registry: what runs (YAML in the release decides what exists). asset_state_events: append-only audit.
CREATE TABLE asset_registry (
  asset_id text COLLATE "C" PRIMARY KEY,
  state text COLLATE "C" NOT NULL CHECK (state IN ('inactive','active','paused','missing')),
  state_since timestamptz NOT NULL, state_by text COLLATE "C" NOT NULL, state_reason text COLLATE "C",
  -- The state a paused asset left, which `asset resume` restores (R-c5); null unless state = 'paused'.
  paused_from text COLLATE "C" CHECK (paused_from IN ('inactive','active')),
  CHECK ((state = 'paused') = (paused_from IS NOT NULL)),
  config_hash text COLLATE "C" NOT NULL, first_seen_release text COLLATE "C",
  last_job_id bigint, last_run_at timestamptz, last_outcome text COLLATE "C");
CREATE TABLE asset_state_events (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, asset_id text COLLATE "C" NOT NULL,
  from_state text COLLATE "C", to_state text COLLATE "C" NOT NULL, at timestamptz NOT NULL, by text COLLATE "C" NOT NULL,
  reason text COLLATE "C", release_tag text COLLATE "C");
CREATE INDEX idx_asset_state_events_asset ON asset_state_events (asset_id, id);
-- latest_levels: the hourly levels job's newest reading per metric (latest-only). watch_state: fire/clear per metric.
CREATE TABLE latest_levels (
  asset_id text COLLATE "C" NOT NULL, metric_key text COLLATE "C" NOT NULL, value double precision NOT NULL,
  observed_at timestamptz NOT NULL, source text COLLATE "C" NOT NULL, block_number bigint, job_id bigint,
  PRIMARY KEY (asset_id, metric_key));
CREATE TABLE watch_state (
  asset_id text COLLATE "C" NOT NULL, metric_key text COLLATE "C" NOT NULL, rule text COLLATE "C" NOT NULL,
  firing boolean NOT NULL, since timestamptz NOT NULL, last_value double precision,
  PRIMARY KEY (asset_id, metric_key));
-- day_blocks: the first block of each UTC day per chain (N9 day-boundary cache).
CREATE TABLE day_blocks (
  chain_id integer NOT NULL, day date NOT NULL, first_block bigint NOT NULL, first_block_ts bigint NOT NULL,
  PRIMARY KEY (chain_id, day));
-- snapshots_out: the snapshot outbox the publisher drains.
CREATE TABLE snapshots_out (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  kind text COLLATE "C" NOT NULL CHECK (kind IN ('full','levels')),
  seq bigint NOT NULL, snapshot_id text COLLATE "C" NOT NULL, sha256 text COLLATE "C" NOT NULL, day date, body json NOT NULL,
  created_at timestamptz NOT NULL, pushed_at timestamptz, attempts integer NOT NULL DEFAULT 0, last_error text COLLATE "C",
  alerted_at timestamptz,
  UNIQUE (kind, seq));
-- daemon_heartbeat: one row per daemon process; drain_requested_at is the drain flag (plan R9).
CREATE TABLE daemon_heartbeat (
  daemon_id text COLLATE "C" PRIMARY KEY, pid integer NOT NULL, host text COLLATE "C" NOT NULL, release_tag text COLLATE "C",
  started_at timestamptz NOT NULL, beat_at timestamptz NOT NULL, current_job_id bigint,
  state text COLLATE "C" NOT NULL CHECK (state IN ('running','draining','drained','stopped')),
  drain_requested_at timestamptz);
